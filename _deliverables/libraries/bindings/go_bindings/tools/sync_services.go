//go:build ignore

// Synchronizes distributable service packages with the shared binding sources.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"
)

var check = flag.Bool("check", false, "check generated sources without writing")

func read(path string) string {
	data, err := os.ReadFile(path)
	if err != nil {
		panic(err)
	}
	return strings.ReplaceAll(string(data), "\r\n", "\n")
}

func between(text, start, end string) string {
	begin := strings.Index(text, start)
	if begin < 0 {
		panic("source marker not found: " + start)
	}
	result := text[begin:]
	if end != "" {
		finish := strings.Index(result, end)
		if finish < 0 {
			panic("source marker not found: " + end)
		}
		result = result[:finish]
	}
	return result
}

func write(path, content string) {
	if filepath.Ext(path) == ".go" {
		content = "// Code generated by tools/sync_services.go; DO NOT EDIT.\n\n" + content
		formatted, err := format.Source([]byte(content))
		if err != nil {
			panic(fmt.Errorf("%s: %w", path, err))
		}
		content = string(formatted)
	}
	if *check {
		if !bytes.Equal([]byte(read(path)), []byte(content)) {
			panic("generated source is out of date: " + path)
		}
		return
	}
	if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
		panic(err)
	}
	if err := os.WriteFile(path, []byte(content), 0644); err != nil {
		panic(err)
	}
}

func main() {
	flag.Parse()
	// Run from the Go bindings directory.
	service := read("service.go")
	bindings := filepath.Join("..", "c_bindings")
	python := filepath.Join("..", "python_bindings")
	header := read(filepath.Join(bindings, "include", "coolbox", "coolbox_c.h"))
	common := between(service, "const serviceErrorCapacity", "type SQLDatabase")
	http := `package http

/*
#cgo CXXFLAGS: -std=c++17 -I${SRCDIR}
#cgo windows LDFLAGS: -lws2_32
#cgo linux LDFLAGS: -pthread
#cgo darwin LDFLAGS: -pthread
#include "coolbox/coolbox_c.h"
#include <stdint.h>
#include <stdlib.h>
extern CoolBoxRouteHandlerV2 coolbox_go_http_handler_pointer(void);
*/
import "C"

import (
	"encoding/json"
	"errors"
	"log"
	"runtime/cgo"
	"strings"
	"sync"
	"unsafe"
)

` + common + between(service, "type HTTPRequest", "")
	write(filepath.Join("http", "server.go"), namespaceHTTP(http))
	write(filepath.Join("http", "web.go"), namespaceHTTP(
		strings.Replace(read("web.go"), "package coolbox", "package http", 1)))
	write(filepath.Join("http", "coolbox", "coolbox_c.h"), namespaceHTTP(header))
	write(filepath.Join("http", "callback.cc"), namespaceHTTP(read("go_http_callback.cc")))
	write(filepath.Join("http", "rest_api", "server.h"),
		read(filepath.Join(python, "include", "rest_api", "server.h")))
	write(filepath.Join("http", "server.cc"),
		read(filepath.Join(python, "src", "rest_api_server.cpp")))
	write(filepath.Join("http", "rest_api", "forms.h"),
		read(filepath.Join(python, "include", "rest_api", "forms.h")))
	write(filepath.Join("http", "web_helpers.cc"),
		read(filepath.Join(python, "src", "web_helpers.cpp")))
	jsonRoot := filepath.Join("..", "..", "groups", "trekker", "IO", "dataformats", "json")
	write(filepath.Join("http", "json.h"), read(filepath.Join(jsonRoot, "headers", "json.h")))
	write(filepath.Join("http", "json.cc"), read(filepath.Join(jsonRoot, "source", "json.cpp")))

	bridge := read(filepath.Join(bindings, "src", "service_bridge.cpp"))
	includes := between(bridge, "#include", "struct CoolBoxSqlDatabase")
	includes = strings.ReplaceAll(includes, "#include \"database.h\"\n", "")
	httpBridge := includes +
		between(bridge, "struct CoolBoxRouteServer", "extern \"C\" {") +
		"extern \"C\" {\n\n" +
		between(bridge, "void coolbox_c_free_string", "CoolBoxSqlDatabase *coolbox_sql_database_create") +
		between(bridge, "CoolBoxRouteServer *coolbox_http_server_create", "")
	write(filepath.Join("http", "bridge.cc"), namespaceHTTP(httpBridge))

	sql := `package sql

/*
#cgo CFLAGS: -I${SRCDIR}
#cgo LDFLAGS: -lcoolbox_c_bindings
#include "coolbox/coolbox_c.h"
#include <stdlib.h>
*/
import "C"

import (
	"encoding/json"
	"errors"
	"sort"
	"sync"
	"unsafe"
)

` + common + between(service, "type SQLDatabase", "type HTTPRequest")
	write(filepath.Join("sql", "database.go"), sql)
	write(filepath.Join("sql", "coolbox", "coolbox_c.h"), header)
	write(filepath.Join("sql", "database_test.go"),
		strings.Replace(read("service_test.go"), "package coolbox", "package sql", 1))
}

func namespaceHTTP(text string) string {
	text = strings.ReplaceAll(text, "coolbox_", "coolbox_isolated_http_")
	return strings.ReplaceAll(text, "coolbox_isolated_http_c.h", "coolbox_c.h")
}
